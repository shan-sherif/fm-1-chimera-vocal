# fm-1-chimera-vocal: the airway's layout and one held vowel, from a `lab record` recording, as a C header for the
# firmware's timing test (app/dsp/voice_male.h). A stand-in until CHIMERA's airway builder (HumanAirway::new) is
# ported to C: the numbers are CHIMERA's (github.com/jamesondh/chimera-vocal-synth, MIT, Jameson Hodge).
#
#   gen_voice_header.py out/male.rec out/male.art > ../app/dsp/voice_male.h
import struct
import sys

REC_MAGIC, ART_MAGIC, BLOCK, END = 4.0e9 + 1729.0, 4.0e9 + 1730.0, -1.0, -2.0


class Reader:
    def __init__(self, path):
        b = open(path, "rb").read()
        self.v = struct.unpack("<%dd" % (len(b) // 8), b)
        self.i = 0

    def f(self):
        x = self.v[self.i]
        self.i += 1
        return x

    def n(self, k):
        return [self.f() for _ in range(k)]


def main(rec_path, art_path):
    r = Reader(rec_path)
    assert r.f() == REC_MAGIC and r.f() == 1.0, "not a version 1 recording"
    fs, ctrl_every, n, nb, nr = r.f(), int(r.f()), int(r.f()), int(r.f()), int(r.f())
    net = r.n(7)
    flags = [int(x) for x in r.n(4)]
    voice = r.n(8)
    r.n(7)
    nodes = [r.n(16) for _ in range(n)]
    nbr_end = int(r.f())
    nbr_list = [int(x) for x in r.n(nbr_end)]
    branches = [r.n(10) for _ in range(nb)]
    blocks = []
    while True:
        tag = r.f()
        if tag == END:
            break
        assert tag == BLOCK
        areas = r.n(n)
        r.n(2 * n + nb)
        nn = int(r.f())
        r.n(6 * nn)
        glottis = r.n(17)
        p_lung = r.f()
        ns = int(r.f())
        r.n(ns)
        blocks.append((glottis, p_lung, areas))

    a = Reader(art_path)
    assert a.f() == ART_MAGIC and a.f() == 1.0, "not a version 1 articulation file"
    art_head = a.n(5 + 3 + 9 + 2 + 3 + 6 + 8)
    a.n(17)
    artic = []
    for _ in blocks:
        artic.append(a.n(17))
        a.f()

    # the held vowel: among the blocks voiced at full breath, the most open one (the widest narrowest point of the
    # pharynx and the mouth)
    n_ph, n_or, ph_first, or_first = int(art_head[5]), int(art_head[6]), int(art_head[11]), int(art_head[14])
    tract = list(range(ph_first, ph_first + n_ph)) + list(range(or_first, or_first + n_or))
    top = max(b[1] for b in blocks)
    voiced = [i for i, (g, p, _) in enumerate(blocks) if p > 0.9 * top and g[1] > 0]
    pick = max(voiced, key=lambda i: min(blocks[i][2][k] for k in tract))
    glottis, p_lung, _ = blocks[pick]
    # and a closure to move to and from (the timing test's worst case: a stop closing and releasing): the blocks
    # where the tract is shut somewhere, at full breath
    shut = [i for i, (g, p, ar) in enumerate(blocks) if p > 0.9 * top and min(ar[k] for k in tract) <= 0.0]
    pick2 = shut[len(shut) // 2] if shut else pick

    f = lambda x: repr(float(x)) + "f"
    arr = lambda xs: "{" + ", ".join(f(x) for x in xs) + "}"
    iarr = lambda xs: "{" + ", ".join(str(int(x)) for x in xs) + "}"
    col = lambda k: [nd[k] for nd in nodes]
    bcol = lambda k: [b[k] for b in branches]
    out = []
    w = out.append
    w("/* SPDX-License-Identifier: MIT")
    w(" * Copyright (c) 2026 Jameson Hodge (CHIMERA, https://github.com/jamesondh/chimera-vocal-synth)")
    w(" * GENERATED by lab/tools/gen_voice_header.py from a `lab record` recording: do not edit.")
    w(" * The adult male airway at %d Hz (%d nodes, %d branches) and one held vowel (control step %d), as CHIMERA" % (fs, n, nb, pick))
    w(" * builds and plays them: the timing test's stand-in until the airway builder is ported to C. */")
    w("#ifndef VOICE_MALE_H\n#define VOICE_MALE_H\n#include \"ch_tract.h\"\n")
    w("#define VM_N %d\n#define VM_NB %d\n#define VM_NR %d\n#define VM_CTRL %d\n#define VM_FS %d\n" % (n, nb, nr, ctrl_every, fs))
    for name, k in (("fixed", 0), ("has_wall", 1), ("rad_of", 8), ("is_junction", 9)):
        w("static const int8_t vm_%s[VM_N] = %s;" % (name, iarr(col(k))))
    for name, k in (("wall_m", 2), ("wall_r", 3), ("wall_k", 4), ("wall_perim", 5), ("wall_rad", 6), ("visc_f", 7),
                    ("area", 10), ("amin", 11), ("dx", 12), ("vol", 13), ("inv_a", 14)):
        w("static const float vm_%s[VM_N] = %s;" % (name, arr(col(k))))
    w("static const uint16_t vm_nbr_start[VM_N + 1] = %s;" % iarr(col(15) + [nbr_end]))
    w("static const uint16_t vm_nbr_list[%d] = %s;" % (nbr_end, iarr(nbr_list)))
    for name, k in (("b_a", 0), ("b_b", 1), ("b_kind", 2), ("port_half", 8)):
        w("static const uint16_t vm_%s[VM_NB] = %s;" % (name, iarr(bcol(k))))
    for name, k in (("port_area", 3), ("port_len", 4), ("port_kin", 5), ("port_kex", 6), ("port_slit", 7),
                    ("port_extra_r", 9)):
        w("static const float vm_%s[VM_NB] = %s;" % (name, arr(bcol(k))))
    w("static const float vm_artic[CH_NARTIC] = %s;   /* the held vowel */" % arr(artic[pick]))
    w("static const float vm_artic2[CH_NARTIC] = %s;   /* a closure (control step %d) */" % (arr(artic[pick2]), pick2))
    w("static const float vm_glottis[17] = %s;   /* its glottis (GlottisParams order) */" % arr(glottis))
    w("static const float vm_p_lung = %s;" % f(p_lung))
    tract_c = """    t->fs = %s; t->n_ph = %d; t->n_or = %d; t->dx_stable = %s;
    t->tr_branch = %d; t->tr_n = %d; t->ph_first = %d; t->ph_branch = %d; t->or_first = %d; t->or_branch = %d;
    t->glottis_port = %d; t->velum_port = %d;
    t->gain_glottis = %s; t->gain_constriction = %s; t->gain_teeth = %s;
    t->max_area_rate = %s; t->area_rate_gain = %s; t->seal_rate = %s; t->seal_lo = %s; t->seal_hi = %s; t->seal_ease = %s;
    t->law[0] = %s; t->law[1] = %s; t->law[2] = %s; t->law[3] = %s; t->law[4] = %s; t->law[5] = %s; t->law[6] = %s; t->law[7] = %s;
    ch_tract_init(t, %s, %s, %s, %s);""" % (
        f(art_head[0]), int(art_head[5]), int(art_head[6]), f(art_head[7]),
        int(art_head[9]), int(art_head[10]), int(art_head[11]), int(art_head[12]), int(art_head[14]), int(art_head[15]),
        int(art_head[17]), int(art_head[18]),
        *map(f, art_head[19:22]), *map(f, art_head[22:28]), *map(f, art_head[28:36]),
        *map(f, art_head[1:5]))
    w("""
/* the anatomy's settings and the body (ch_tract_init): all the waveguide (ch_wave.c) needs */
static void vm_tract_setup(ch_tract_t *t)
{
%s
}

/* the full-physics voice's topology and starting state (ch_fast_init_state after), and the anatomy's settings */
static void vm_setup(ch_voice_t *v, ch_tract_t *t)
{
    int k;
    v->fs = %s;
    v->ctrl_every = VM_CTRL;
    v->n = VM_N;
    v->nb = VM_NB;
    v->nr = VM_NR;
    v->closed_area = %s; v->min_node_area = %s; v->viscous_scale = %s; v->viscous_omega = %s;
    v->noise_scale = %s; v->squeeze_area = %s; v->vol_lp_coef = %s;
    v->enable_volume_source = %d; v->enable_junction_floor = %d; v->energy_safe = %d; v->symmetric_kinetic = %d;
    v->output_gain = %s; v->dc_coef = %s; v->lim_hold_n = %d; v->lim_release = %s;
    v->glottis_port = %d; v->lungs = %d; v->sub_node = %d; v->supra = %d;
    for (k = 0; k < VM_N; k++) {
        v->fixed[k] = (uint8_t)vm_fixed[k]; v->has_wall[k] = (uint8_t)vm_has_wall[k]; v->rad_of[k] = vm_rad_of[k];
        v->is_junction[k] = (uint8_t)vm_is_junction[k]; v->wall_m[k] = vm_wall_m[k]; v->wall_r[k] = vm_wall_r[k];
        v->wall_k[k] = vm_wall_k[k]; v->wall_perim[k] = vm_wall_perim[k]; v->wall_rad[k] = vm_wall_rad[k];
        v->visc_f[k] = vm_visc_f[k]; v->area[k] = vm_area[k]; v->amin[k] = vm_amin[k]; v->dx[k] = vm_dx[k];
        v->vol[k] = vm_vol[k]; v->inv_a[k] = vm_inv_a[k]; v->nbr_start[k] = vm_nbr_start[k];
    }
    v->nbr_start[VM_N] = vm_nbr_start[VM_N];
    for (k = 0; k < (int)vm_nbr_start[VM_N]; k++)
        v->nbr_list[k] = vm_nbr_list[k];
    for (k = 0; k < VM_NB; k++) {
        v->b_a[k] = vm_b_a[k]; v->b_b[k] = vm_b_b[k]; v->b_kind[k] = (uint8_t)vm_b_kind[k];
        v->port_half[k] = (uint8_t)vm_port_half[k]; v->port_area[k] = vm_port_area[k]; v->port_len[k] = vm_port_len[k];
        v->port_kin[k] = vm_port_kin[k]; v->port_kex[k] = vm_port_kex[k]; v->port_slit[k] = vm_port_slit[k];
        v->port_extra_r[k] = vm_port_extra_r[k];
    }
    vm_tract_setup(t);
}
#endif""" % (tract_c,
        f(fs), *map(f, net), *flags, f(voice[0]), f(voice[1]), int(voice[2]), f(voice[3]), *[int(x) for x in voice[4:8]]))
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
