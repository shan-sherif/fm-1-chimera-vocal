# header for the firmware (app/dsp/phrase_male.h), which speaks it through the C control (engine/ch_control.c). A
# stand-in until CHIMERA's text front end and planner are ported: the numbers are CHIMERA's
# (github.com/jamesondh/chimera-vocal-synth, MIT, Jameson Hodge).
#
#   gen_phrase_header.py out/male.gst "She sells sea shells." > ../app/dsp/phrase_male.h
import struct
import sys

GST_MAGIC = 4.0e9 + 1731.0
NCONTROL = 22


def num(x):
    if x != x:
        return "NA"
    s = repr(float(x))
    return s + "f" if ("." in s or "e" in s) else s + ".0f"


def main(path, text):
    b = open(path, "rb").read()
    v = struct.unpack("<%dd" % (len(b) // 8), b)
    assert v[0] == GST_MAGIC and v[1] == 1.0, "not a version 1 gestures file"
    ng = int(v[2])
    src = v[3:15]
    body, max_pen, f0 = v[15:18]
    i = 18
    out = []
    w = out.append
    w("/* SPDX-License-Identifier: MIT")
    w(" * Copyright (c) 2026 Jameson Hodge (CHIMERA, https://github.com/jamesondh/chimera-vocal-synth)")
    w(" * Generated by lab/tools/gen_phrase_header.py from a CHIMERA recording: do not edit.")
    w(" *")
    w(' * "%s": the gestures CHIMERA planned for it (times in seconds from the start), its voice source. */' % text)
    w("#ifndef PHRASE_MALE_H")
    w("#define PHRASE_MALE_H")
    w('#include "ch_control.h"')
    w("#define NA __builtin_nanf(\"\")")
    w("#define PH_TEXT \"%s\"" % text.upper())
    w("#define PH_BODY_SCALE %s" % num(body))
    w("#define PH_MAX_PENETRATION %s" % num(max_pen))
    w("#define PH_F0_START %s" % num(f0))
    w("#define PH_N %d" % ng)
    w("static const ch_source_t ph_source = {%s, %d, %s};" % (", ".join(num(x) for x in src[:10]), int(src[10]), num(src[11])))
    w("/* t0, t1, ramp_in, ramp_out, strength, speed, release_hold, tag; the targets (NA: not this gesture's) */")
    w("static const ch_gesture_t ph_gestures[PH_N] = {")
    for _ in range(ng):
        g = v[i:i + 8 + NCONTROL]
        i += 8 + NCONTROL
        w("    {%s, {%s}}," % (", ".join(num(x) for x in g[:8]), ", ".join(num(x) for x in g[8:])))
    w("};")
    w("#undef NA")
    w("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "")
